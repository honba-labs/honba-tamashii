//! Unit tests for `crate::native`.

use crate::native::*;

#[test]
fn the_stub_declares_every_class_and_function() {
    let names = declared_names();
    assert!(names.contains(&"Price"));
    assert!(names.contains(&"Quantity"));
    assert!(names.contains(&"Money"));
    assert!(names.contains(&"InstrumentId"));
    assert!(names.contains(&"RiskEngine"));
    assert!(names.contains(&"verify_manifest"));
    assert!(names.contains(&"SCHEMA_VERSION"));
}

#[test]
fn the_stub_is_marked_as_generated() {
    let stub = render_pyi();
    assert!(stub.contains("DO NOT EDIT"));
    assert!(stub.contains("Generated by honba-codegen"));
}

#[test]
fn every_stub_line_is_annotated() {
    // `mypy --strict` is the acceptance test: a definition without an
    // annotation is an error there, so it is an error here.
    let stub = render_pyi();
    for line in stub.lines() {
        let trimmed = line.trim();
        if trimmed.is_empty() || trimmed.starts_with('#') || trimmed.starts_with('"') {
            continue;
        }
        if trimmed.starts_with("def ") {
            assert!(
                trimmed.contains("-> "),
                "unannotated function: {trimmed}"
            );
            continue;
        }
        if trimmed.ends_with(':') && !trimmed.starts_with("class ") {
            continue;
        }
        if trimmed.starts_with("class ") || trimmed.starts_with("pass") {
            continue;
        }
        assert!(
            trimmed.contains(": "),
            "unannotated attribute: {trimmed}"
        );
    }
}

#[test]
fn the_stub_imports_what_it_annotates() {
    let stub = render_pyi();
    assert!(stub.contains("import datetime"));
    assert!(stub.contains("import decimal"));
    assert!(stub.contains("from typing import Any"));
}
