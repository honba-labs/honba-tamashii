//! Markdown documentation rendered from the endpoint registry and domain types.
//!
//! This artifact keeps the published docs in sync with the Rust source of truth:
//! the REST table is derived from [`honba_messages::ENDPOINTS`] / `WRITE_PATHS`
//! and the type lists from [`crate::registry`]. Regenerate with `make docs`; the
//! committed copy lives in the sibling `honba-docs` checkout.

use crate::endpoints::{is_stream, request_type_for, response_type_for};
use crate::registry::{
    API_TYPES, CONFIG_TYPES, MANIFEST_TYPES, SCREENER_TYPES, WIRE_ENUMS, WIRE_TYPES,
    request_type_names,
};
use honba_messages::{ENDPOINTS, WRITE_PATHS};

/// Renders the full Markdown documentation.
pub fn render(schema_version: u32, api_version: &str) -> String {
    let mut out = String::new();
    out.push_str(&header(schema_version, api_version));
    out.push_str(&rest_reference());
    out.push_str(&domain_types_reference());
    out
}

/// The page title and generation banner.
fn header(schema_version: u32, api_version: &str) -> String {
    format!(
        "# Honba API Reference\n\n\
         <!-- Generated by honba-codegen from the Rust source of truth. DO NOT EDIT: regenerate with `make docs`. -->\n\n\
         - Wire schema version: `{schema_version}`\n\
         - API version: `{api_version}`\n\n\
         This page is generated from the endpoint registry (`crates/honba-messages/src/endpoints.rs`)\n\
         and the published type registry (`crates/honba-codegen/src/registry.rs`), so it cannot drift\n\
         from the served API. Regenerate with `make docs`.\n\n\
         ---\n\n"
    )
}

/// The REST endpoint table.
fn rest_reference() -> String {
    let mut out = String::new();
    out.push_str("## REST endpoints\n\n");
    out.push_str("Every response is a `ResponseEnvelope<T>`; the table names the payload `T`.\n\n");
    out.push_str("| Method | Path | Access | Request | Response | Stream |\n");
    out.push_str("| --- | --- | --- | --- | --- | --- |\n");
    for (method, path) in ENDPOINTS {
        let request = request_type_for(method, path).unwrap_or("—");
        let response = response_type_for(method, path).unwrap_or("ResponseEnvelope");
        let stream = if is_stream(method, path) {
            "text/event-stream"
        } else {
            "—"
        };
        out.push_str(&format!(
            "| `{method}` | `{path}` | {} | `{request}` | `{response}` | {stream} |\n",
            access_label(method, path)
        ));
    }
    out.push('\n');
    out
}

/// The published domain type lists, grouped by registry section.
fn domain_types_reference() -> String {
    let mut out = String::new();
    out.push_str("## Domain types\n\n");
    out.push_str("Types generated into the JSON Schema, TypeScript, `.pyi` and MCP artifacts.\n\n");

    let sections: &[(&str, &[&str])] = &[
        ("Wire types", WIRE_TYPES),
        ("Screener types", SCREENER_TYPES),
        ("Enums", WIRE_ENUMS),
        ("API types", API_TYPES),
        ("Manifest types", MANIFEST_TYPES),
        ("Config types", CONFIG_TYPES),
    ];
    for (title, names) in sections {
        out.push_str(&format!("### {title}\n\n"));
        for name in *names {
            out.push_str(&format!("- `{name}`\n"));
        }
        out.push('\n');
    }

    out.push_str("### Request DTOs\n\n");
    for name in request_type_names() {
        out.push_str(&format!("- `{name}`\n"));
    }
    out.push('\n');

    out.push_str("### Response DTOs\n\n");
    let mut response_types: Vec<&str> = ENDPOINTS
        .iter()
        .filter_map(|(method, path)| response_type_for(method, path))
        .collect();
    response_types.sort_unstable();
    response_types.dedup();
    for name in response_types {
        out.push_str(&format!("- `{name}`\n"));
    }
    out.push('\n');
    out
}

/// `write` when the route is in [`WRITE_PATHS`], otherwise `read`.
fn access_label(method: &str, path: &str) -> &'static str {
    if WRITE_PATHS.iter().any(|(m, p)| *m == method && *p == path) {
        "write"
    } else {
        "read"
    }
}
